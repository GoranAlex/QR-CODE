create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  password_hash text not null,
  role text not null default 'scanner',
  client_id text,
  must_change_password boolean not null default false,
  password_changed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists users_email_lower_idx
on public.users (lower(email));

create table if not exists public.app_settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.users(id)
);

create table if not exists public.attendees (
  id text primary key,
  name text not null,
  email text not null default '',
  unique_id text not null default '',
  qr_code text not null,
  qr_code_normalized text not null unique,
  company text not null default '',
  ticket_type text not null default '',
  admission_item text not null default '',
  sessions text not null default '',
  photo text not null default '',
  checked_in boolean not null default false,
  check_in_time timestamptz,
  checked_in_by uuid references public.users(id),
  goodie_bag boolean not null default false,
  goodie_bag_time timestamptz,
  goodie_bag_by uuid references public.users(id),
  imported_at timestamptz not null default now(),
  source_row integer not null default 0,
  original jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.scan_attempts (
  id bigint generated by default as identity primary key,
  staff_user_id uuid not null references public.users(id) on delete cascade,
  ip_address text not null default 'unknown',
  code_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists attendees_qr_code_normalized_idx
on public.attendees (qr_code_normalized);

create index if not exists attendees_status_idx
on public.attendees (checked_in);

create index if not exists attendees_goodie_bag_idx
on public.attendees (goodie_bag);

create index if not exists attendees_search_idx on public.attendees
using gin (
  to_tsvector(
    'simple',
    coalesce(name, '') || ' ' ||
      coalesce(email, '') || ' ' ||
      coalesce(unique_id, '') || ' ' ||
      coalesce(qr_code, '') || ' ' ||
      coalesce(company, '') || ' ' ||
      coalesce(ticket_type, '')
  )
);

create index if not exists scan_attempts_staff_created_idx
on public.scan_attempts (staff_user_id, created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.set_attendee_qr_code_normalized()
returns trigger
language plpgsql
as $$
begin
  new.qr_code_normalized = lower(trim(new.qr_code));
  return new;
end;
$$;

drop trigger if exists set_app_settings_updated_at on public.app_settings;
create trigger set_app_settings_updated_at
before update on public.app_settings
for each row
execute function public.set_updated_at();

drop trigger if exists set_users_updated_at on public.users;
create trigger set_users_updated_at
before update on public.users
for each row
execute function public.set_updated_at();

drop trigger if exists set_attendees_updated_at on public.attendees;
create trigger set_attendees_updated_at
before update on public.attendees
for each row
execute function public.set_updated_at();

drop trigger if exists set_attendee_qr_code_normalized on public.attendees;
create trigger set_attendee_qr_code_normalized
before insert or update of qr_code on public.attendees
for each row
execute function public.set_attendee_qr_code_normalized();

insert into public.app_settings (key, value)
values ('event_name', 'Event Check-In')
on conflict (key) do nothing;
